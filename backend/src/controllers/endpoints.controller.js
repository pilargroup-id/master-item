const {
  API_BASE_PATH,
  commonResponses,
  endpointGroups,
  getAllEndpoints,
  getEndpointSummary,
} = require('../docs/restApiEndpoints');

function listToText(items) {
  if (!items || items.length === 0) return '-';
  return items.join(', ');
}

function renderMarkdown() {
  const summary = getEndpointSummary();
  const lines = [
    '# REST API Endpoint List',
    '',
    'Backend-generated reference for frontend and backend teams.',
    '',
    '## Overview',
    '',
    `- Base path: \`${API_BASE_PATH}\``,
    `- Total groups: ${summary.totalGroups}`,
    `- Total endpoints: ${summary.totalEndpoints}`,
    `- Public endpoints: ${summary.auth.public}`,
    `- Protected endpoints: ${summary.auth.protected}`,
    '',
    '## Response Contract',
    '',
    '```json',
    JSON.stringify(commonResponses, null, 2),
    '```',
    '',
  ];

  endpointGroups.forEach((group) => {
    lines.push(`## ${group.group}`);
    lines.push('');
    lines.push(group.description);
    lines.push('');
    lines.push('| Method | Endpoint | Auth | Roles | Query | Body | Description |');
    lines.push('| --- | --- | --- | --- | --- | --- | --- |');

    group.endpoints.forEach((endpoint) => {
      lines.push([
        endpoint.method,
        `\`${endpoint.path}\``,
        endpoint.auth ? 'Yes' : 'No',
        listToText(endpoint.roles),
        listToText(endpoint.query),
        listToText(endpoint.body),
        endpoint.summary,
      ].join(' | '));
    });

    lines.push('');
  });

  return lines.join('\n');
}

const list = (req, res) => {
  const wantsMarkdown = req.query.format === 'markdown';

  if (wantsMarkdown) {
    res.type('text/markdown').send(renderMarkdown());
    return;
  }

  res.json({
    success: true,
    message: 'REST API endpoint list generated by backend.',
    data: {
      summary: getEndpointSummary(),
      responseContract: commonResponses,
      groups: endpointGroups,
      endpoints: getAllEndpoints(),
    },
  });
};

const markdown = (req, res) => {
  res.type('text/markdown').send(renderMarkdown());
};

module.exports = { list, markdown };

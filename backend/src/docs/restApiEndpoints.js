function getAllEndpoints() {
  return endpointGroups.flatMap((group) =>
    group.endpoints.map((endpoint) => ({
      group: group.group,
      description: group.description,
      ...endpoint,
    }))
  );
}

function getEndpointSummary() {
  const endpoints = getAllEndpoints();
  return {
    basePath: API_BASE_PATH,
    totalGroups: endpointGroups.length,
    totalEndpoints: endpoints.length,
    byMethod: endpoints.reduce((summary, endpoint) => {
      summary[endpoint.method] = (summary[endpoint.method] || 0) + 1;
      return summary;
    }, {}),
    auth: {
      public: endpoints.filter((endpoint) => !endpoint.auth).length,
      protected: endpoints.filter((endpoint) => endpoint.auth).length,
    },
  };
}

